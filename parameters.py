"""define all global parameters here."""
import argparse
import os
import sys
from os.path import join
import pcode.models as models
from pcode.utils.param_parser import str2bool

def get_args():
    ROOT_DIRECTORY = './'
    RAW_DATA_DIRECTORY = join(ROOT_DIRECTORY, 'data/')
    TRAINING_DIRECTORY = join(ROOT_DIRECTORY, 'checkpoint')
    model_names = sorted((name for name in models.__dict__ if name.islower() and (not name.startswith('__'))))
    parser = argparse.ArgumentParser(description='PyTorch Training for ConvNet')
    parser.add_argument('--port', default='50021', type=str)
    parser.add_argument('--data', default='cifar10', help='a specific dataset name')
    parser.add_argument('--prepare_data', default=None, type=str)
    parser.add_argument('--val_data_ratio', type=float, default=0.0)
    parser.add_argument('--train_data_ratio', type=float, default=0.5)
    parser.add_argument('--test_data_ratio', type=float, default=0.5)
    parser.add_argument('--data_dir', default=RAW_DATA_DIRECTORY, help='path to dataset')
    parser.add_argument('--use_fake_centering', type=str2bool, default=False)
    parser.add_argument('--partition_data', default=None, type=str, help='decide if each worker will access to all data.')
    parser.add_argument('--shard_per_user', default=2, type=int)
    parser.add_argument('--pin_memory', default=True, type=str2bool)
    parser.add_argument('-j', '--num_workers', default=4, type=int, help='number of data loading workers (default: 4)')
    parser.add_argument('--pn_normalize', default=True, type=str2bool, help='normalize by mean/std.')
    parser.add_argument('--algo', default='fedscad', type=str, choices=['fedscad', 'fedga'])
    parser.add_argument('--arch', default='cnn_mlp', help='model architecture: ' + ' | '.join(model_names) + ' (default: resnet20)')
    parser.add_argument('--complex_arch', type=str, default=None)
    parser.add_argument('--w_conv_bias', default=True, type=str2bool)
    parser.add_argument('--w_fc_bias', default=False, type=str2bool)
    parser.add_argument('--resnet_scaling', default=1, type=float)
    parser.add_argument('--bessel_mode', default='approx', type=str)
    parser.add_argument('--estimator_dtype', default='float32', type=str)
    parser.add_argument('--estimator_update_every', default=1, type=int)
    parser.add_argument('--kd_warmup_rounds', default=0, type=int)
    parser.add_argument('--agce_warmup_rounds', '--scl_warmup_rounds', dest='agce_warmup_rounds', default=0, type=int)
    parser.add_argument('--use_logit_adjust', default=False, type=str2bool)
    parser.add_argument('--kd_weight', '--global_fc_kd_weight', dest='kd_weight', default=0.0, type=float)
    parser.add_argument('--use_hc', '--use_feddyn', dest='use_hc', default=False, type=lambda x: str(x).lower() in ['true', '1', 't', 'y'])
    parser.add_argument('--hc_weight', '--feddyn_alpha', dest='hc_weight', default=0.01, type=float)
    parser.add_argument('--ce_weight', default=1.0, type=float)
    parser.add_argument('--n_comm_rounds', type=int, default=90)
    parser.add_argument('--target_perf', type=float, default=None, help='it is between [0, 100].')
    parser.add_argument('--early_stopping_rounds', type=int, default=0)
    parser.add_argument('--local_n_epochs', type=int, default=1)
    parser.add_argument('--random_reinit_local_model', default=None, type=str)
    parser.add_argument('--local_prox_term', type=float, default=0)
    parser.add_argument('--min_local_epochs', type=float, default=None)
    parser.add_argument('--batch_size', '-b', default=256, type=int, help='mini-batch size (default: 256)')
    parser.add_argument('--base_batch_size', default=None, type=int)
    parser.add_argument('--n_clients', default=1, type=int, help='# of the clients for federated learning.')
    parser.add_argument('--participation_ratio', default=0.1, type=float, help='number of participated ratio per communication rounds')
    parser.add_argument('--n_participated', default=None, type=int)
    parser.add_argument('--fl_aggregate', default=None, type=str)
    parser.add_argument('--non_iid_alpha', default=0.05, type=float)
    parser.add_argument('--train_fast', type=str2bool, default=False)
    parser.add_argument('--use_mixup', default=False, type=str2bool)
    parser.add_argument('--mixup_alpha', default=1.0, type=float)
    parser.add_argument('--mixup_noniid', default=False, type=str2bool)
    parser.add_argument('--mlp_lr_ratio', default=1.0, type=float, help='Learning rate ratio for MLP head')
    parser.add_argument('--fc_lr_ratio', default=1.0, type=float, help='Learning rate ratio for FC classifier')
    parser.add_argument('--lr', type=float, default=0.01)
    parser.add_argument('--lr_scheduler', type=str, default='MultiStepLR', choices=['MultiStepLR', 'ExponentialLR', 'ReduceLROnPlateau'])
    parser.add_argument('--lr_milestones', type=str, default=None)
    parser.add_argument('--lr_milestone_ratios', type=str, default=None)
    parser.add_argument('--lr_decay', type=float, default=0.1)
    parser.add_argument('--lr_scaleup', type=str2bool, default=False)
    parser.add_argument('--lr_scaleup_init_lr', type=float, default=None)
    parser.add_argument('--lr_scaleup_factor', type=int, default=None)
    parser.add_argument('--lr_warmup', type=str2bool, default=False)
    parser.add_argument('--lr_warmup_epochs', type=int, default=None)
    parser.add_argument('--lr_warmup_epochs_upper_bound', type=int, default=150)
    parser.add_argument('--adam_beta_1', default=0.9, type=float)
    parser.add_argument('--adam_beta_2', default=0.999, type=float)
    parser.add_argument('--adam_eps', default=1e-08, type=float)
    parser.add_argument('--optimizer', type=str, default='sgd')
    parser.add_argument('--local_model_compression', type=str, default=None)
    parser.add_argument('--momentum_factor', default=0.9, type=float)
    parser.add_argument('--use_nesterov', default=False, type=str2bool)
    parser.add_argument('--weight_decay', default=0.0005, type=float, help='weight decay (default: 1e-4)')
    parser.add_argument('--self_distillation', default=0.3, type=float)
    parser.add_argument('--kd_temperature', '--self_distillation_temperature', dest='kd_temperature', default=4, type=float)
    parser.add_argument('--same_seed_process', type=str2bool, default=True)
    parser.add_argument('--manual_seed', type=int, default=6, help='manual seed')
    parser.add_argument('--summary_freq', default=256, type=int)
    parser.add_argument('--timestamp', default=None, type=str)
    parser.add_argument('--track_time', default=False, type=str2bool)
    parser.add_argument('--track_gpu_memory', default=False, type=str2bool, help='save per-worker CUDA allocator snapshots to checkpoint_root/gpu_memory')
    parser.add_argument('--gpu_memory_interval', default=10, type=int, help='sample every N communication rounds; rounds 1-3 are always sampled')
    parser.add_argument('--display_tracked_time', default=False, type=str2bool)
    parser.add_argument('--track_communication', default=str2bool(os.environ.get('TRACK_COMMUNICATION', 'False')), type=str2bool, help='record application-level distributed tensor bytes on the server; writes communication_rounds.csv and communication_summary.json')
    parser.add_argument('--display_communication', default=str2bool(os.environ.get('DISPLAY_COMMUNICATION', 'False')), type=str2bool, help='print per-round downlink/uplink payload when communication tracking is enabled')
    parser.add_argument('--personal_test', default=False, type=str2bool)
    parser.add_argument('--combine_personal_split', default=True, type=str2bool, help="when prepare_data=combine, split each client's local train/test by ratios")
    parser.add_argument('--server_eval_global_test', default=True, type=str2bool, help="evaluate on server's original global test set")
    parser.add_argument('--server_eval_client_tests', default=False, type=str2bool, help="evaluate on each client's local test set (personal evaluation)")
    parser.add_argument('--resume', default=None, type=str)
    parser.add_argument('--checkpoint', '-c', default=TRAINING_DIRECTORY, type=str, help='path to save checkpoint (default: checkpoint)')
    parser.add_argument('--save_all_models', type=str2bool, default=False)
    parser.add_argument('--save_some_models', type=str, default=None)
    parser.add_argument('--feature_similarity_probe_rounds', type=str, default=None, help='comma-separated communication rounds to save cross-client same-class feature similarity for selected local models')
    parser.add_argument('--feature_similarity_n_clients', type=int, default=10)
    parser.add_argument('--feature_similarity_classes', type=str, default=None, help='comma-separated class ids for the feature-similarity probe; defaults to the first 10 classes')
    parser.add_argument('--feature_similarity_feature_source', type=str, default='pre_classifier', choices=['pre_classifier', 'projection', 'auto'], help='which feature to use when model returns a tuple: pre_classifier uses output[2], projection uses output[0], auto prefers output[2]')
    parser.add_argument('--feature_similarity_max_batches', type=int, default=0, help='optional cap on server-test batches per local model for the feature-similarity probe; 0 means use all')
    parser.add_argument('--feature_similarity_save_samples', type=str2bool, default=True, help='save sample-level projection, pre-classifier features, logits, labels, and indices in the probe npz')
    parser.add_argument('--feature_similarity_samples_per_class', type=int, default=200, help='maximum sample-level records saved per class and client; 0 means save all available samples')
    parser.add_argument('--feature_similarity_sample_dtype', type=str, default='float16', choices=['float16', 'float32'], help='floating-point dtype for sample-level arrays in the probe npz')
    parser.add_argument('--feature_similarity_out_dir', type=str, default=None, help='optional output directory for feature-similarity probe artifacts; defaults to checkpoint_root/feature_similarity')
    parser.add_argument('--feature_similarity_save_tsne', type=str2bool, default=True, help='also save a t-SNE plot of client-class feature centers')
    parser.add_argument('--feature_similarity_tsne_perplexity', type=float, default=10.0)
    parser.add_argument('--feature_similarity_tsne_point_size', type=float, default=70.0)
    parser.add_argument('--feature_similarity_tsne_alpha', type=float, default=0.88)
    parser.add_argument('--feature_similarity_tsne_annotate_clients', type=str2bool, default=False, help='annotate each t-SNE prototype point with its client id')
    parser.add_argument('--python_path', type=str, default=sys.executable)
    parser.add_argument('--world', default=None, type=str)
    parser.add_argument('--world_conf', default=None, type=str)
    parser.add_argument('--on_cuda', type=str2bool, default=True)
    'meta info.'
    parser.add_argument('--experiment', type=str, default='debug')
    parser.add_argument('--job_id', type=str, default='/tmp/jobrun_logs')
    parser.add_argument('--anchor_temperature', '--proco_temp', dest='anchor_temperature', default=0.1, type=float)
    parser.add_argument('--feat_dim', default=128, type=int)
    parser.add_argument('--cnn_mlp_cifar_simple', default=False, type=str2bool)
    parser.add_argument('--agce_weight', '--proco_alpha', dest='agce_weight', default=0.2, type=float)
    parser.add_argument('--anchor_init', '--fedga_global_init', dest='anchor_init', default='etf', type=str, choices=['etf', 'random', 'paired_class'], help='Fixed shared simplex ETF, random unit anchors, or one anchor per adjacent class pair.')
    # Ignored compatibility flag; the released pipeline always uses one view.
    parser.add_argument('--proco_single_view', default=False, type=str2bool, help=argparse.SUPPRESS)
    parser.add_argument('--plot_data_distribution', default=False, type=str2bool, help='Whether to plot and save the class distribution heatmap.')
    conf = parser.parse_args()
    return conf
if __name__ == '__main__':
    args = get_args()
